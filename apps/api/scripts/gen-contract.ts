import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';
import { parse } from 'yaml';

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

const API_ROOT = new URL('../', import.meta.url);
export const CONTRACT_PATH = fileURLToPath(
  new URL('../../docs/api/openapi.yaml', API_ROOT),
);
export const OUTPUTS = {
  types: fileURLToPath(new URL('src/contract/types.gen.ts', API_ROOT)),
  openapi: fileURLToPath(new URL('src/contract/openapi.gen.ts', API_ROOT)),
};

const HEADER =
  '// Generated by scripts/gen-contract.ts from docs/api/openapi.yaml. Do not edit; run `pnpm --filter api contract:gen`.\n';
const ANNOTATIONS = new Set(['description', 'example', 'examples', 'summary']);
const METHODS = ['get', 'post', 'put', 'patch', 'delete'] as const;

export async function generate(
  yamlText: string,
): Promise<{ types: string; openapi: string }> {
  const doc = parse(yamlText) as JsonObject;
  const types = HEADER + astToString(await openapiTS(doc as never));
  return {
    types: await pretty(types, OUTPUTS.types),
    openapi: await pretty(emitOpenapi(doc), OUTPUTS.openapi),
  };
}

function emitOpenapi(doc: JsonObject): string {
  const components = doc.components as JsonObject;
  const schemas = components.schemas as JsonObject;
  const defs: JsonObject = {};
  for (const [name, schema] of Object.entries(schemas)) {
    defs[name] = inline(doc, schema, '#/$defs/');
  }

  const operations: JsonObject = {};
  for (const [path, item] of Object.entries(doc.paths as JsonObject)) {
    for (const method of METHODS) {
      const op = (item as JsonObject)[method] as JsonObject | undefined;
      if (!op) continue;
      operations[op.operationId as string] = inline(
        doc,
        {
          method,
          path,
          parameters: op.parameters ?? [],
          requestBody: requestBodyOf(op),
          responses: op.responses,
        },
        'contract#/$defs/',
      );
    }
  }

  return [
    HEADER,
    "import type { OperationSpec } from './index.js';",
    "import type { operations } from './types.gen.js';",
    '',
    `export const CONTRACT_SCHEMA = ${JSON.stringify({ $id: 'contract', $defs: defs })};`,
    '',
    `export const OPERATIONS = ${JSON.stringify(operations)} satisfies Record<keyof operations, OperationSpec>;`,
    '',
  ].join('\n');
}

function requestBodyOf(op: JsonObject): Json {
  const body = op.requestBody as JsonObject | undefined;
  if (!body) return null;
  const [[contentType, media]] = Object.entries(body.content as JsonObject);
  return { contentType, schema: (media as JsonObject).schema };
}

/** Resolves response and parameter refs in place and points schema refs at `schemaBase`. Drops annotations. */
function inline(
  doc: JsonObject,
  node: Json,
  schemaBase: string,
  isPropertyMap = false,
): Json {
  if (Array.isArray(node)) return node.map((n) => inline(doc, n, schemaBase));
  if (node === null || typeof node !== 'object') return node;
  const ref = node.$ref;
  if (typeof ref === 'string') {
    const schema = ref.match(/^#\/components\/schemas\/(\w+)$/);
    if (schema) return { $ref: schemaBase + schema[1] };
    return inline(doc, lookup(doc, ref), schemaBase);
  }
  const out: JsonObject = {};
  for (const [key, value] of Object.entries(node)) {
    if (!isPropertyMap && ANNOTATIONS.has(key)) continue;
    out[key] = inline(doc, value, schemaBase, key === 'properties');
  }
  return out;
}

function lookup(doc: JsonObject, ref: string): Json {
  let node: Json = doc;
  for (const part of ref.replace(/^#\//, '').split('/')) {
    node = (node as JsonObject)[part];
    if (node === undefined) throw new Error(`Unresolvable $ref ${ref}`);
  }
  return node;
}

async function pretty(source: string, file: string): Promise<string> {
  const options = await resolveConfig(file);
  return format(source, { ...options, filepath: file });
}

if (import.meta.main) {
  const out = await generate(await readFile(CONTRACT_PATH, 'utf8'));
  await writeFile(OUTPUTS.types, out.types);
  await writeFile(OUTPUTS.openapi, out.openapi);
  console.log(`Wrote ${OUTPUTS.types}\nWrote ${OUTPUTS.openapi}`);
}
